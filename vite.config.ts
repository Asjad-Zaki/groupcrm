const createHtmlPlugin = ({
  inject,
}: {
  inject?: { data?: Record<string, string> };
  minify?: boolean;
} = {}): Plugin => ({
  name: "vite-plugin-simple-html",
  transformIndexHtml: {
    order: "pre",
    handler(html: string) {
      let result = html;
      if (inject?.data) {
        for (const [key, value] of Object.entries(inject.data)) {
          result = result.replaceAll(
            new RegExp(`<%=\\s*${key}\\s*%>`, "g"),
            value,
          );
        }
      }
      return result;
    },
  },
});

