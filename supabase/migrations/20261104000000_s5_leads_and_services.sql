-- S5: Leads and services
--
-- This migration adds lead/deal stage management, stage transitions config,
-- lead sources, and HIGH_RISK flag support.
--
-- Changes:
-- 1. Adds lead-specific columns to public.deals: stage check constraint,
--    high_risk, next_follow_up, reason, owner_id, converted_at, lead_source,
--    contacted_at
-- 2. Creates public.lead_sources table for lead origin tracking
-- 3. Creates public.stage_transitions table for valid stage transitions
--    per organization
-- 4. Creates public.stage_history table for audit trail of stage changes
-- 5. Adds trigger validate_deal_stage_transition() for enforcing transition rules
-- 6. Adds trigger on_deals_stage_transition for automatic stage history logging
--

-- Add lead-specific columns to public.deals
alter table public.deals
    add column high_risk boolean not null default false;

alter table public.deals
    add column next_follow_up timestamp with time zone;

alter table public.deals
    add column reason text;

alter table public.deals
    add column owner_id uuid references public.sales(id) on update cascade on delete set null;

alter table public.deals
    add column converted_at timestamp with time zone;

alter table public.deals
    add column lead_source text;

alter table public.deals
    add column contacted_at timestamp with time zone;

-- Create lead_sources table
create table public.lead_sources (
    id bigint generated by default as identity primary key,
    name text not null,
    value text,
    organization_id bigint references public.organizations(id) on update cascade on delete set null,
    created_at timestamp with time zone not null default now()
);

