    ('Cold Call', 'cold_call', null),
    ('Referral', 'referral', null),
    ('Trade Show', 'trade_show', null),
    ('Email Campaign', 'email_campaign', null);

-- Create stage_transitions table
create table public.stage_transitions (
    id bigint generated by default as identity primary key,
    from_stage text not null,
    to_stage text not null,
    organization_id bigint references public.organizations(id) on update cascade on delete cascade,
    allowed boolean not null default true,
    reason_required boolean not null default false,
    created_at timestamp with time zone not null default now(),
    unique (from_stage, to_stage, organization_id)
);

