-- S1: Rename companies to organizations and add company model support
--
-- This migration renames public.companies to public.organizations and creates
-- the supporting tables for company membership, roles, and permissions.
--

-- Rename companies table to organizations
alter table public.companies rename to organizations;

-- Update foreign keys to reference organizations instead of companies
alter table public.contacts
    drop constraint contacts_company_id_fkey,
    add constraint contacts_organization_id_fkey foreign key (company_id) references public.organizations(id) on update cascade on delete cascade;

alter table public.deals
    drop constraint deals_company_id_fkey,
    add constraint deals_organization_id_fkey foreign key (company_id) references public.organizations(id) on update cascade on delete cascade;

-- Create departments table
create table public.departments (
    id bigint generated by default as identity primary key,
    name text not null,
    organization_id bigint not null references public.organizations(id) on update cascade on delete cascade,
    created_at timestamp with time zone not null default now(),
    unique (name, organization_id)
);

-- Create roles table
create table public.roles (
    id bigint generated by default as identity primary key,
    name text not null,
    description text,
    organization_id bigint not null references public.organizations(id) on update cascade on delete cascade,
    created_at timestamp with time zone not null default now(),
    unique (name, organization_id)
);

-- Create role_permissions table (junction table for role-based access)
create table public.role_permissions (
    id bigint generated by default as identity primary key,
    role_id bigint not null references public.roles(id) on update cascade on delete cascade,
    permission text not null,
    resource text not null,
    allowed boolean not null default true,
    created_at timestamp with time zone not null default now(),
    unique (role_id, permission, resource)
);

-- Create user_company_memberships table
create table public.user_company_memberships (
    id bigint generated by default as identity primary key,
    user_id uuid not null references auth.users(id) on update cascade on delete cascade,
    organization_id bigint not null references public.organizations(id) on update cascade on delete cascade,
    role_id bigint references public.roles(id) on update,
    status text not null default 'pending' check (status in ('pending', 'approved', 'revoked', 'temporary')),
    is_temporary boolean not null default false,
    effective_from timestamp with time zone,
    effective_to timestamp with time zone,
    review_by uuid references auth.users(id),
    approved_by uuid references auth.users(id),
    created_at timestamp with time zone not null default now(),
    unique (user_id, organization_id)
);

-- Indexes for user_company_memberships
create index idx_user_company_memberships_user_id on public.user_company_memberships (user_id);
create index idx_user_company_memberships_org_id on public.user_company_memberships (organization_id);
create index idx_user_company_memberships_role_id on public.user_company_memberships (role_id);
create index idx_user_company_memberships_status on public.user_company_memberships (status);

